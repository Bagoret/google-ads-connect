#!/usr/bin/env python3
"""List UNKNOWN fields in context/*.md, split into blockers and optional context, and write
a data-readiness checklist to outputs/onboarding/data-readiness.md.

Usage: python3 scripts/context_status.py [--context-dir context] [--out outputs/onboarding]
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# (file, field-name prefix) pairs without which analysis would be misleading.
BLOCKING = {
    ("business.md", "Account currency"),
    ("business.md", "Account timezone"),
    ("business.md", "Trading / marketplace brand name"),
    ("business.md", "Stocked product brands"),
    ("business.md", "Primary country / market"),
    ("business.md", "Main language(s) customers search in"),
    ("account-map.md", "Customer ID"),
    ("account-map.md", "Account(s) in scope"),
    ("measurement.md", "Conversion actions"),
    ("measurement.md", "Conversion value ="),
}

SEPARATOR = re.compile(r"^\|[\s:|-]+\|\s*$")


@dataclass
class Field:
    file: str
    section: str
    name: str
    value: str
    blocking: bool


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def scan_context(context_dir: Path) -> list[Field]:
    fields: list[Field] = []
    for path in sorted(Path(context_dir).glob("*.md")):
        section = ""
        lines = path.read_text(encoding="utf-8").splitlines()
        headers = {i - 1 for i, line in enumerate(lines) if SEPARATOR.match(line)}
        for i, line in enumerate(lines):
            if line.startswith("## "):
                section = line[3:].strip()
                continue
            if not line.startswith("|") or i in headers or SEPARATOR.match(line):
                continue
            cells = _cells(line)
            if cells[0].upper().startswith("UNKNOWN"):
                name, value = section, "UNKNOWN"
            elif len(cells) > 1 and cells[1].upper().startswith("UNKNOWN"):
                name, value = cells[0], cells[1]
            else:
                continue
            blocking = any(path.name == f and name.startswith(p) for f, p in BLOCKING)
            fields.append(Field(path.name, section, name, value, blocking))
    return fields


def readiness_markdown(fields: list[Field], mcp_configured: bool, snapshots: list[str]) -> str:
    blockers = [f for f in fields if f.blocking]
    optional = [f for f in fields if not f.blocking]
    L = ["# Data readiness", "",
         "Generated by `scripts/context_status.py`. Credentials are configured locally in `.mcp.json` / your "
         "environment — never share tokens, secrets, or passwords in chat or in these files.", "",
         f"## Blockers ({len(blockers)})", ""]
    L += [f"- [ ] `{f.file}` › {f.section} › **{f.name}**" for f in blockers] or ["- None."]
    L += ["", f"## Optional context ({len(optional)})", ""]
    L += [f"- [ ] `{f.file}` › {f.section} › {f.name}" for f in optional] or ["- None."]
    L += ["", "## MCP and data checklist", "",
          f"- [{'x' if mcp_configured else ' '}] `.mcp.json` configured for the official Google Ads MCP server "
          "(see `docs/mcp-setup.md`)",
          "- [ ] `python3 scripts/check_connection.py --live --customer-id <ID>` passes (OAuth, server, account access)",
          f"- [{'x' if snapshots else ' '}] First snapshot saved: "
          "`python3 scripts/snapshot.py --query customer_settings --customer-id <ID>`",
          "- [ ] Contract gate: `python3 scripts/inspect_snapshot.py <snapshot>` shows a known shape and no unmapped "
          "required fields",
          "- [ ] Campaign inventory snapshot taken and `config/campaign_classification.json` filled",
          "- [ ] Brand lists filled in `config/brand_lists.json`", "",
          "## Analyses unlocked once blockers are cleared", "",
          "| Analysis | Queries needed |", "|---|---|",
          "| Weekly review | campaign_daily |",
          "| Search-term review | search_terms, keywords, negative_keywords, shared_negative_keywords, campaign_shared_sets |",
          "| Product review | product_daily (+ optional margin/stock supplement) |",
          "| Measurement audit | conversion_actions |", ""]
    if snapshots:
        L += ["## Snapshots found", "", *[f"- `{s}`" for s in snapshots], ""]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--context-dir", type=Path, default=ROOT / "context")
    ap.add_argument("--out", type=Path, default=ROOT / "outputs" / "onboarding")
    args = ap.parse_args(argv)
    fields = scan_context(args.context_dir)
    snapshots = sorted(p.name for p in (ROOT / "data" / "raw").glob("*.json"))
    md = readiness_markdown(fields, (ROOT / ".mcp.json").exists(), snapshots)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "data-readiness.md").write_text(md, encoding="utf-8")
    blockers = [f for f in fields if f.blocking]
    print(f"{len(blockers)} blocker(s), {len(fields) - len(blockers)} optional UNKNOWN field(s)")
    for f in blockers:
        print(f"BLOCKER  {f.file} › {f.name}")
    print(args.out / "data-readiness.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
